"""Generate QUERIES.md from the source: every Cypher string passed to ``ctx.q(...)`` inside a registered tool,
plus the memory/task/verifier queries. Keeps the submission document in sync with the code that runs.

    python scripts/gen_queries.py
"""
from __future__ import annotations

import ast
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = [
    ("Tools (agent-callable, also served over MCP)", sorted((ROOT / "tbk/tools").glob("*.py"))),
    ("Verifier", [ROOT / "tbk/verifier.py", ROOT / "tbk/tools/common.py"]),
    ("Coordination (tasks and handoffs)", [ROOT / "tbk/tasks.py"]),
    ("Memory (episodic, semantic, actions)", [ROOT / "tbk/memory.py"]),
    ("Graph schema and indexes", [ROOT / "tbk/seed/load.py"]),
]


def render(node: ast.AST) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        out = []
        for v in node.values:
            out.append(v.value if isinstance(v, ast.Constant) else "{" + ast.unparse(v.value) + "}")
        return "".join(out)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        a, b = render(node.left), render(node.right)
        return a + b if a is not None and b is not None else None
    return None


KEYWORDS = ("OPTIONAL MATCH", "MATCH", "WHERE", "RETURN", "ORDER BY", "WITH", "CALL", "CREATE", "SET", "MERGE",
            "UNWIND", "LIMIT", "DETACH DELETE")


def tidy(q: str) -> str:
    """Break a one-line query before each top-level clause (not inside parentheses/brackets)."""
    q, out, depth, i = q.strip(), [], 0, 0
    while i < len(q):
        ch = q[i]
        depth += ch in "([{"
        depth -= ch in ")]}"
        if depth == 0 and i > 0 and q[i - 1] == " ":
            kw = next((k for k in KEYWORDS if q.startswith(k, i) and not q[i + len(k):i + len(k) + 1].isalnum()), None)
            if kw and not q[:i].rstrip().endswith("OPTIONAL"):
                out[-1] = out[-1].rstrip()
                out.append("\n")
        out.append(ch)
        i += 1
    return "".join(out)


def main() -> None:
    out = ["# Cypher and graph algorithms the product depends on", "",
           "Generated by `python scripts/gen_queries.py` from the code that executes them (do not edit by hand). "
           "`$name` are query parameters; `{n}` marks an integer depth that is range-checked and interpolated "
           "(Cypher cannot parameterise variable-length bounds).", ""]
    for title, files in FILES:
        out += [f"## {title}", ""]
        for f in files:
            if f.name == "__init__.py" or not f.exists():
                continue
            tree = ast.parse(f.read_text())
            for fn in [n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef)]:
                qs = []
                for call in [c for c in ast.walk(fn) if isinstance(c, ast.Call)]:
                    name = ast.unparse(call.func)
                    if name.endswith((".q", "g.query", "_try")) and call.args:
                        arg = call.args[-1] if name.endswith("_try") else call.args[0]
                        s = render(arg)
                        if s and re.search(r"\b(MATCH|CALL|CREATE|MERGE|UNWIND)\b", s):
                            qs.append(tidy(s))
                if not qs:
                    continue
                ref = ""
                for d in fn.decorator_list:
                    if isinstance(d, ast.Call) and getattr(d.func, "id", "") == "tool":
                        ref = next((ast.literal_eval(k.value) for k in d.keywords if k.arg == "cypher_ref"), "")
                        doc = ast.literal_eval(d.args[1]) if len(d.args) > 1 else ""
                        out += [f"### `{fn.name}` — {ref}", "", doc, ""]
                        break
                else:
                    out += [f"### `{f.relative_to(ROOT)}::{fn.name}`", ""]
                for q in dict.fromkeys(qs):
                    out += ["```cypher", q, "```", ""]
    (ROOT / "QUERIES.md").write_text("\n".join(out))
    print("wrote QUERIES.md", len(out), "lines")


if __name__ == "__main__":
    main()
