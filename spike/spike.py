"""Phase 0 spike: confirm FalkorDB features we depend on (see NOTES.md)."""
from falkordb import FalkorDB
db = FalkorDB(port=6390)
g = db.select_graph("spike")
try: g.delete()
except Exception: pass
g = db.select_graph("spike")
def t(label, fn):
    try: print("OK  ", label, "->", fn())
    except Exception as e: print("FAIL", label, "->", str(e)[:160])
t("create", lambda: g.query("UNWIND range(1,6) AS i CREATE (:S {id:i})").nodes_created)
t("edges", lambda: g.query("MATCH (a:S),(b:S) WHERE b.id=a.id+1 CREATE (a)-[:D {vf:1}]->(b)").relationships_created)
t("procedures", lambda: [r[0] for r in g.query("CALL dbms.procedures() YIELD name RETURN name").result_set if r[0].startswith(('algo','db.idx'))])
t("pagerank", lambda: g.query("CALL algo.pageRank('S','D') YIELD node, score RETURN node.id, score ORDER BY score DESC LIMIT 2").result_set)
t("wcc", lambda: g.query("CALL algo.WCC() YIELD node, componentId RETURN count(DISTINCT componentId)").result_set)
t("betweenness", lambda: g.query("CALL algo.betweenness({nodeLabels:['S'], relationshipTypes:['D']}) YIELD node, score RETURN node.id, score ORDER BY score DESC LIMIT 2").result_set)
t("bfs", lambda: g.query("MATCH (s:S {id:1}) CALL algo.BFS(s, 3, 'D') YIELD nodes, edges RETURN size(nodes)").result_set)
t("shortestPath", lambda: g.query("MATCH (a:S {id:1}),(b:S {id:5}) MATCH p=shortestPath((a)-[:D*]->(b)) RETURN length(p)").result_set)
t("varlen", lambda: g.query("MATCH p=(a:S {id:6})<-[:D*1..4]-(d) RETURN DISTINCT d.id ORDER BY d.id").result_set)
t("all rel filter", lambda: g.query("MATCH p=(a:S {id:6})<-[:D*1..4]-(d) WHERE ALL(r IN relationships(p) WHERE r.vf <= 1) RETURN count(p)").result_set)
t("id(r)", lambda: g.query("MATCH ()-[r:D]->() WHERE ID(r) IN [0,1] RETURN ID(r), type(r)").result_set)
t("vec idx", lambda: g.query("CREATE VECTOR INDEX FOR (d:Doc) ON (d.embedding) OPTIONS {dimension:4, similarityFunction:'cosine'}").indices_created)
t("vec ins", lambda: g.query("CREATE (:Doc {id:1, embedding: vecf32([1,0,0,0])}), (:Doc {id:2, embedding: vecf32([0,1,0,0])})").nodes_created)
t("vec q", lambda: g.query("CALL db.idx.vector.queryNodes('Doc','embedding',2,vecf32([1,0.1,0,0])) YIELD node, score RETURN node.id, score").result_set)
t("fulltext", lambda: g.query("CALL db.idx.fulltext.createNodeIndex('Doc','title')"))
t("explain", lambda: str(g.explain("MATCH (s:S {id:1}) RETURN s"))[:80])
t("props list", lambda: g.query("CREATE (:X {tags:['a','b']})").nodes_created)
t("params", lambda: g.query("MATCH (s:S {id:$i}) RETURN s.id", {"i": 3}).result_set)
t("case/min", lambda: g.query("MATCH (s:S) RETURN min(s.id), CASE WHEN count(s)>3 THEN 1 ELSE 0 END").result_set)
